// Package emit 把生成计划渲染为完整的 nftables ruleset 文本。
package emit

import (
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/lixiangzhong/efw/internal/ir"
	"github.com/lixiangzhong/efw/internal/optimize"
)

const (
	indentTable    = ""
	indentSet      = "    "
	indentSetField = "        "
	indentChain    = "        "

	// forwardChainName/forwardPriority：内置容器转发链（仅匹配 DNAT 流量）。
	forwardChainName = "forward"
	forwardPriority  = "-10"

	// masqueradeChainName/masqueradePriority：出站源 NAT 链。
	// 90 先于 Docker/Netavark/Tailscale 的 srcnat(100)，显式规则优先；
	// 同优先级跨表顺序不保证，不能依赖。
	masqueradeChainName = "postrouting"
	masqueradePriority  = "90"
)

// baseInternal4/baseInternal6 是默认放行的本机/非 RFC1918 来源。
// RFC1918（10/8、172.16/12、192.168/16）默认不放行；容器运行时网段由 apply 探测后追加。
var (
	baseInternal4 = []string{"100.64.0.0/10", "127.0.0.0/8", "169.254.0.0/16"}
	baseInternal6 = []string{"::1", "fc00::/7", "fe80::/10"}
)

// Options 是产物头的元信息与部署参数。
type Options struct {
	Table     string
	Chain     string
	Hook      string
	Priority  string
	LogPrefix string
	Version   string
	Source    string
	Stamp     bool
	Now       time.Time
	// UnreachableLines 是 W1 告警涉及的行号，产物中会加 unreachable 注释。
	UnreachableLines map[int]bool
}

// internalSourceSets 生成 input/forward 最前面的来源放行集合：
// 默认含 CGNAT/loopback/link-local 与 IPv6 ULA/link-local/回环；
// RFC1918 不默认放行，容器来源由 ACL 里的 `iface br-*` / `iface docker0` 显式信任。
func internalSourceSets() (string, string) {
	return "{ " + strings.Join(baseInternal4, ", ") + " }", "{ " + strings.Join(baseInternal6, ", ") + " }"
}

// Render 渲染完整可加载的 ruleset。同一输入与选项必须产出字节级相同结果。
func Render(f *ir.File, plan optimize.Plan, opts Options) []byte {
	var b strings.Builder

	b.WriteString("#!/usr/sbin/nft -f\n")
	fmt.Fprintf(&b, "# Generated by efw v%s\n", opts.Version)
	fmt.Fprintf(&b, "# source: %s\n", commentText(opts.Source))
	fallback, _ := f.Fallback()
	fmt.Fprintf(&b, "# policy: accept | fallback: %s | established: %s | v6-bootstrap: %s | forward: %s\n",
		fallback, autoWord(f.Established), autoWord(f.V6Bootstrap), autoWord(f.Forward))
	if opts.Stamp {
		fmt.Fprintf(&b, "# generated: %s\n", opts.Now.UTC().Format(time.RFC3339))
	}
	b.WriteString("\n")

	fmt.Fprintf(&b, "%stable inet %s {\n", indentTable, opts.Table)
	sets := append([]optimize.Set(nil), plan.Sets...)
	if usesPrivate(plan) || masqueradeUsesPrivate(f) {
		sets = append(sets,
			optimize.Set{Name: ir.Private4SetName, Kind: optimize.KindIPv4, Elements: ir.Private4Prefixes},
			optimize.Set{Name: ir.Private6SetName, Kind: optimize.KindIPv6, Elements: ir.Private6Prefixes},
		)
		sort.Slice(sets, func(i, j int) bool { return sets[i].Name < sets[j].Name })
	}
	for _, set := range sets {
		renderSet(&b, set)
	}

	renderChain(&b, f, plan, opts, opts.Chain, opts.Hook, opts.Priority, false)
	if f.Forward {
		b.WriteString("\n")
		renderChain(&b, f, plan, opts, forwardChainName, "forward", forwardPriority, true)
	}
	if len(f.Masquerades) > 0 {
		b.WriteString("\n")
		renderMasqueradeChain(&b, f.Masquerades)
	}

	b.WriteString("}\n")
	return []byte(b.String())
}

func renderChain(b *strings.Builder, f *ir.File, plan optimize.Plan, opts Options, name, hook, priority string, forward bool) {
	fmt.Fprintf(b, "%schain %s {\n", indentSet, name)
	fmt.Fprintf(b, "%stype filter hook %s priority %s; policy accept;\n", indentChain, hook, priority)
	b.WriteString("\n")

	if forward {
		fmt.Fprintf(b, "%s# 说明: 本链只匹配 DNAT 转发流量（如容器发布端口）\n\n", indentChain)
	}
	if !forward {
		fmt.Fprintf(b, "%s# auto: 本机回环放行（本机访问自身地址也走 lo）\n", indentChain)
		fmt.Fprintf(b, "%siifname \"lo\" accept\n\n", indentChain)
	}
	internal4, internal6 := internalSourceSets()
	fmt.Fprintf(b, "%s# auto: 本机/CGNAT/link-local 来源放行（RFC1918 默认不放；容器来源由 iface 规则显式信任）\n", indentChain)
	fmt.Fprintf(b, "%sip saddr %s accept\n", indentChain, internal4)
	fmt.Fprintf(b, "%sip6 saddr %s accept\n\n", indentChain, internal6)
	if f.Established {
		fmt.Fprintf(b, "%s# auto: 已建立连接放行\n", indentChain)
		fmt.Fprintf(b, "%sct state established,related accept\n\n", indentChain)
	}
	if !forward && f.V6Bootstrap && f.FallbackDeny() {
		fmt.Fprintf(b, "%s# auto: IPv6 邻居发现（NDP）\n", indentChain)
		fmt.Fprintf(b, "%sip6 nexthdr ipv6-icmp icmpv6 type { nd-neighbor-solicit, nd-neighbor-advert, nd-router-solicit, nd-router-advert } accept\n\n", indentChain)
		fmt.Fprintf(b, "%s# auto: DHCPv6\n", indentChain)
		fmt.Fprintf(b, "%sudp dport { 546, 547 } accept\n\n", indentChain)
	}

	for i, rule := range plan.Rules {
		if i > 0 {
			b.WriteString("\n")
		}
		renderRule(b, rule, opts.LogPrefix, opts.UnreachableLines, forward)
	}

	fmt.Fprintf(b, "%s}\n", indentSet)
}

func renderSet(b *strings.Builder, set optimize.Set) {
	fmt.Fprintf(b, "%sset %s {\n", indentSet, set.Name)
	fmt.Fprintf(b, "%stype %s\n", indentSetField, setType(set.Kind))
	fmt.Fprintf(b, "%sflags interval\n", indentSetField)
	fmt.Fprintf(b, "%selements = { %s }\n", indentSetField, strings.Join(set.Elements, ", "))
	fmt.Fprintf(b, "%s}\n\n", indentSet)
}

// renderMasqueradeChain 渲染出站源 NAT 链；NAT 首条匹配生效，条目顺序必须与书写顺序一致。
// 链优先于容器运行时/尾网的 srcnat(100)，且只在存在 masquerade 规则时生成。
func renderMasqueradeChain(b *strings.Builder, entries []ir.Masquerade) {
	fmt.Fprintf(b, "%schain %s {\n", indentSet, masqueradeChainName)
	fmt.Fprintf(b, "%stype nat hook postrouting priority %s; policy accept;\n\n", indentChain, masqueradePriority)
	fmt.Fprintf(b, "%s# 说明: 出站源 NAT；首条匹配生效，顺序即书写顺序\n", indentChain)
	for i, entry := range entries {
		if i > 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(b, "%s# %d: %s\n", indentChain, entry.Line, commentText(strings.TrimSpace(entry.Raw)))
		for _, text := range masqueradeTexts(entry) {
			fmt.Fprintf(b, "%s%s\n", indentChain, text)
		}
	}
	fmt.Fprintf(b, "%s}\n", indentSet)
}

// masqueradeTexts 返回一条 NAT 规则的产物文本：private 固定展开 v4/v6 两条。
func masqueradeTexts(entry ir.Masquerade) []string {
	if entry.Src.Named == ir.PrivateName {
		return []string{
			fmt.Sprintf("ip saddr @%s oifname %q masquerade", ir.Private4SetName, entry.Iface),
			fmt.Sprintf("ip6 saddr @%s oifname %q masquerade", ir.Private6SetName, entry.Iface),
		}
	}
	if entry.Src.Any {
		return []string{fmt.Sprintf("oifname %q masquerade", entry.Iface)}
	}
	family := "ip"
	if entry.Src.Family == ir.FamilyIPv6 {
		family = "ip6"
	}
	return []string{fmt.Sprintf("%s saddr %s oifname %q masquerade", family, entry.Src.Value, entry.Iface)}
}

func renderRule(b *strings.Builder, r optimize.Rule, logPrefix string, unreachable map[int]bool, forward bool) {
	for i := range r.Lines {
		fmt.Fprintf(b, "%s# %d: %s\n", indentChain, r.Lines[i], commentText(strings.TrimSpace(r.Raws[i])))
		if unreachable[r.Lines[i]] {
			fmt.Fprintf(b, "%s# W1: unreachable（与前面的规则匹配重复，不会被命中）\n", indentChain)
		}
	}
	for _, text := range ruleTexts(r, logPrefix, forward) {
		fmt.Fprintf(b, "%s%s\n", indentChain, text)
	}
}

// ruleTexts 返回一条规则对应的产物文本。
// private 是独立源地址规则，固定展开 v4/v6 两条；
// forward 链另有两类端口拆分约束（否则内核中 ct original proto-dst 会变成 invalid type）：
//   - 协议省略 + 端口：拆成 tcp/udp 两条（proto-dst 需要显式单协议上下文）；
//   - 端口为多个内联值/范围：拆成每条一个值/范围（内联集合 + proto-dst 无效，命名 set 有效）。
func ruleTexts(r optimize.Rule, logPrefix string, forward bool) []string {
	families := []ir.Family{ir.FamilyAny}
	if hasPrivate(r) {
		families = []ir.Family{ir.FamilyIPv4, ir.FamilyIPv6}
	}
	texts := make([]string, 0, len(families))
	for _, family := range families {
		texts = append(texts, familyRuleTexts(r, logPrefix, forward, family)...)
	}
	return texts
}

// hasPrivate 报告规则是否用 private 作为源地址。
func hasPrivate(r optimize.Rule) bool {
	return r.Src.Named == ir.PrivateName
}

// usesPrivate 报告产物是否需要 private4/private6 集合。
func usesPrivate(plan optimize.Plan) bool {
	for _, r := range plan.Rules {
		if hasPrivate(r) {
			return true
		}
	}
	return false
}

// masqueradeUsesPrivate 报告 masquerade 规则是否引用 private 集合。
func masqueradeUsesPrivate(f *ir.File) bool {
	for _, m := range f.Masquerades {
		if m.Src.Named == ir.PrivateName {
			return true
		}
	}
	return false
}

func familyRuleTexts(r optimize.Rule, logPrefix string, forward bool, family ir.Family) []string {
	if !forward {
		return []string{ruleText(r, logPrefix, false, family)}
	}
	protos := []ir.Proto{r.Proto}
	if r.Proto == ir.ProtoAny && !r.Ports.IsAny() {
		protos = []ir.Proto{ir.ProtoTCP, ir.ProtoUDP}
	}
	texts := make([]string, 0, len(protos))
	for _, proto := range protos {
		rule := r
		rule.Proto = proto
		// 命名 set 在 forward 侧有效；单值/单范围可内联；多个内联范围必须拆。
		if rule.Ports.SetName != "" || len(rule.Ports.Ranges) <= 1 {
			texts = append(texts, ruleText(rule, logPrefix, forward, family))
			continue
		}
		for _, portRange := range rule.Ports.Ranges {
			one := rule
			one.Ports = optimize.Ports{Ranges: []ir.PortRange{portRange}}
			texts = append(texts, ruleText(one, logPrefix, forward, family))
		}
	}
	return texts
}

func ruleText(r optimize.Rule, logPrefix string, forward bool, family ir.Family) string {
	parts := make([]string, 0, 8)
	if forward {
		parts = append(parts, "ct status dnat")
	}
	if r.Iface != "" {
		parts = append(parts, ifaceExpr(r.Iface))
	}
	if !r.Src.Any {
		parts = append(parts, addressExpr("saddr", r.Src, family))
	}
	if !r.Dst.Any {
		if forward {
			parts = append(parts, originalDstExpr(r.Dst, family))
		} else {
			parts = append(parts, addressExpr("daddr", r.Dst, family))
		}
	}
	if forward {
		parts = append(parts, forwardProtoExpr(r)...)
	} else {
		parts = append(parts, protoExpr(r)...)
	}
	if r.Log || r.LogOnly {
		parts = append(parts, fmt.Sprintf("log prefix \"%s\" level info", logPrefix))
	}
	if !r.LogOnly {
		parts = append(parts, r.Verdict.String())
	}
	return strings.Join(parts, " ")
}

// originalDstExpr 在 forward 链中按 DNAT 前的目的地址匹配（发布地址语义）。
func originalDstExpr(a optimize.Address, family ir.Family) string {
	fam := "ip"
	if a.Family == ir.FamilyIPv6 {
		fam = "ip6"
	}
	if a.SetName != "" {
		return fmt.Sprintf("ct original %s daddr @%s", fam, a.SetName)
	}
	return fmt.Sprintf("ct original %s daddr %s", fam, a.Value)
}

// addressExpr 生成地址匹配表达式；family 用于 private 源地址的地址族展开。
func addressExpr(direction string, a optimize.Address, family ir.Family) string {
	if a.Named == ir.PrivateName {
		if family == ir.FamilyIPv6 {
			return fmt.Sprintf("ip6 %s @%s", direction, ir.Private6SetName)
		}
		return fmt.Sprintf("ip %s @%s", direction, ir.Private4SetName)
	}
	fam := "ip"
	if a.Family == ir.FamilyIPv6 {
		fam = "ip6"
	}
	if a.SetName != "" {
		return fmt.Sprintf("%s %s @%s", fam, direction, a.SetName)
	}
	return fmt.Sprintf("%s %s %s", fam, direction, a.Value)
}

// ifaceExpr 生成入口网卡匹配（按名字匹配，避免编译机与目标机的网卡索引差异）。
func ifaceExpr(name string) string {
	return fmt.Sprintf("iifname %q", name)
}

// protoExpr 生成协议/端口匹配表达式。
func protoExpr(r optimize.Rule) []string {
	switch r.Proto {
	case ir.ProtoTCP:
		if r.Ports.IsAny() {
			return []string{"meta l4proto tcp"}
		}
		return []string{"tcp dport", portsExpr(r.Ports)}
	case ir.ProtoUDP:
		if r.Ports.IsAny() {
			return []string{"meta l4proto udp"}
		}
		return []string{"udp dport", portsExpr(r.Ports)}
	case ir.ProtoICMP:
		return []string{"meta l4proto { icmp, ipv6-icmp }"}

	// 单地址族变体：先限定 nfproto，再匹配具体协议/端口。
	case ir.ProtoTCP4:
		return familyProtoExpr("ipv4", "tcp", r.Ports)
	case ir.ProtoTCP6:
		return familyProtoExpr("ipv6", "tcp", r.Ports)
	case ir.ProtoUDP4:
		return familyProtoExpr("ipv4", "udp", r.Ports)
	case ir.ProtoUDP6:
		return familyProtoExpr("ipv6", "udp", r.Ports)
	case ir.ProtoICMP4:
		return []string{"meta nfproto ipv4 meta l4proto icmp"}
	case ir.ProtoICMP6:
		return []string{"meta nfproto ipv6 meta l4proto ipv6-icmp"}

	default:
		if r.Ports.IsAny() {
			return nil
		}
		return []string{"meta l4proto { tcp, udp } th dport", portsExpr(r.Ports)}
	}
}

// forwardProtoExpr 在 forward 链中按 DNAT 前的端口匹配（ct original proto-dst）。
// nft 要求该表达式带 l4proto 守卫，故每种协议都显式写出协议匹配。
func forwardProtoExpr(r optimize.Rule) []string {
	switch r.Proto {
	case ir.ProtoTCP:
		if r.Ports.IsAny() {
			return []string{"meta l4proto tcp"}
		}
		return []string{"meta l4proto tcp ct original proto-dst", portsExpr(r.Ports)}
	case ir.ProtoUDP:
		if r.Ports.IsAny() {
			return []string{"meta l4proto udp"}
		}
		return []string{"meta l4proto udp ct original proto-dst", portsExpr(r.Ports)}
	case ir.ProtoICMP:
		return []string{"meta l4proto { icmp, ipv6-icmp }"}
	case ir.ProtoTCP4:
		return forwardFamilyProtoExpr("ipv4", "tcp", r.Ports)
	case ir.ProtoTCP6:
		return forwardFamilyProtoExpr("ipv6", "tcp", r.Ports)
	case ir.ProtoUDP4:
		return forwardFamilyProtoExpr("ipv4", "udp", r.Ports)
	case ir.ProtoUDP6:
		return forwardFamilyProtoExpr("ipv6", "udp", r.Ports)
	case ir.ProtoICMP4:
		return []string{"meta nfproto ipv4 meta l4proto icmp"}
	case ir.ProtoICMP6:
		return []string{"meta nfproto ipv6 meta l4proto ipv6-icmp"}
	default:
		// ProtoAny + 端口由 ruleTexts 拆成 tcp/udp 两条；协议集合形式在内核中
		// 会让 ct original proto-dst 变成 invalid type，不能在此生成。
		return nil
	}
}

func forwardFamilyProtoExpr(nfproto, proto string, ports optimize.Ports) []string {
	parts := []string{"meta nfproto " + nfproto + " meta l4proto " + proto}
	if ports.IsAny() {
		return parts
	}
	return append(parts, "ct original proto-dst", portsExpr(ports))
}

// familyProtoExpr 生成「限定地址族 + 具体协议（可带端口）」的匹配表达式。
func familyProtoExpr(nfproto, proto string, ports optimize.Ports) []string {
	parts := []string{"meta nfproto " + nfproto}
	if ports.IsAny() {
		return append(parts, "meta l4proto "+proto)
	}
	return append(parts, proto+" dport", portsExpr(ports))
}

func portsExpr(p optimize.Ports) string {
	if p.SetName != "" {
		return "@" + p.SetName
	}
	if len(p.Ranges) == 1 && p.Ranges[0].Lo == p.Ranges[0].Hi {
		return p.Ranges[0].String()
	}
	items := make([]string, len(p.Ranges))
	for i, r := range p.Ranges {
		items[i] = r.String()
	}
	return "{ " + strings.Join(items, ", ") + " }"
}

func setType(kind string) string {
	switch kind {
	case optimize.KindIPv4:
		return "ipv4_addr"
	case optimize.KindIPv6:
		return "ipv6_addr"
	default:
		return "inet_service"
	}
}

// commentText 把可能破坏单行注释的字符折叠成空格（如路径中的换行）。
func commentText(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r == '\n' || r == '\r' || r < 0x20 || r == 0x7f {
			b.WriteByte(' ')
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

func autoWord(on bool) string {
	if on {
		return "auto"
	}
	return "off"
}
